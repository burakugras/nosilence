defmodule NosilenceWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :nosilence

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_nosilence_key",
    signing_salt: "lNCOZUv5",
    same_site: "Lax"
  ]

  # Real-time gateway. The ticket travels in the WebSocket handshake header
  # (`auth_token`); the Origin must be our own web app.
  socket "/socket", NosilenceWeb.Gateway.Socket,
    auth_token: true,
    websocket: [check_origin: {NosilenceWeb.Endpoint, :allowed_origin?, []}],
    longpoll: false

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :nosilence,
    gzip: not code_reloading?,
    only: NosilenceWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :nosilence
  end

  plug NosilenceWeb.DesktopCors
  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug NosilenceWeb.Router

  @doc "Only the web app's own origin and the desktop app may open the gateway connection."
  def allowed_origin?(%URI{} = origin) do
    app = URI.parse(Application.fetch_env!(:nosilence, :app_url))

    (origin.scheme == app.scheme and origin.host == app.host and origin.port == app.port) or
      URI.to_string(%{origin | path: nil}) in NosilenceWeb.UserAuth.desktop_origins()
  end
end
