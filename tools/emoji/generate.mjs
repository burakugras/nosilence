// Builds the emoji list for reactions (ADR 0017) from Unicode's emoji-test.txt:
//   - client/src/ui/emojiData.json: the picker's groups, each emoji with its name
//   - server/priv/emoji.txt: one emoji per line, the only reactions the server accepts
//
// Emoji 12.0, because Windows 10 draws emoji up to that version; newer ones show
// as empty boxes there. Only fully-qualified emoji without skin tones.
//
// Usage: download https://unicode.org/Public/emoji/12.0/emoji-test.txt, then
//   node tools/emoji/generate.mjs <path to emoji-test.txt>
// The data is © Unicode, Inc., under the Unicode License (https://www.unicode.org/license.txt).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const source = process.argv[2]
if (!source) {
  console.error('Usage: node tools/emoji/generate.mjs <emoji-test.txt>')
  process.exit(2)
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const text = readFileSync(source, 'utf8')
if (!/^# Version: 12\.0$/m.test(text)) {
  console.error('Expected emoji-test.txt version 12.0')
  process.exit(1)
}

const SKIPPED_GROUPS = new Set(['Component'])
const groups = []
let group
for (const line of text.split(/\r?\n/)) {
  const header = line.match(/^# group: (.+)$/)
  if (header) {
    group = SKIPPED_GROUPS.has(header[1]) ? undefined : { name: header[1], emoji: [] }
    if (group) groups.push(group)
    continue
  }
  // "1F600 ; fully-qualified # 😀 grinning face"
  const entry = line.match(/^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+(.+)$/)
  if (!group || !entry) continue
  const [, emoji, name] = entry
  if (/skin tone/.test(name)) continue
  group.emoji.push([emoji, name])
}

const all = groups.flatMap((g) => g.emoji.map(([e]) => e))
if (new Set(all).size !== all.length) throw new Error('duplicate emoji')

writeFileSync(
  join(root, 'client/src/ui/emojiData.json'),
  JSON.stringify({ version: '12.0', groups }) + '\n',
)
writeFileSync(
  join(root, 'server/priv/emoji.txt'),
  '# Generated by tools/emoji/generate.mjs from Unicode emoji-test.txt 12.0 (© Unicode, Inc.).\n' +
    all.join('\n') +
    '\n',
)
console.log(`${groups.length} groups, ${all.length} emoji`)
